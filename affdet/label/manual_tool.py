"""Manual pair-labelling tool — human ground truth for experiment E3.

Every affordance label in this thesis was generated by a VLM whose quality has
never been independently measured. This tool produces the human labels that
turn "the student matches its teacher" into "the student is correct", and is
the only path to showing the student beating the teacher it learned from.

**The labeller must be blind to both the VLM label and the model prediction.**
If either is visible while judging, the human label becomes partly a function
of what was shown, and "human agrees with VLM 92% of the time" measures
anchoring rather than agreement — a number that still computes but no longer
means what the thesis claims. That is enforced structurally here: the pair
list may not carry those fields at all (see BLIND_FIELD_PATTERNS), and
load_pair_list raises rather than quietly ignoring them. The join against VLM
labels and model predictions happens offline, afterwards, on `pair_id`.

Protocol: tools/docs/labeling_protocol.md (frozen; read before a session).

Run:
    python -m affdet.label.manual_tool --pairs <list.json> --out <session.jsonl>
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import webbrowser
from datetime import datetime, timezone
from functools import lru_cache
from http.server import BaseHTTPRequestHandler, HTTPServer
from pathlib import Path
from typing import Any, Iterable

from affdet.label.prompts import AFFORDANCE_QUESTION, _CALIBRATION
from affdet.label.vlm import VLM_PREDICATES

SCHEMA_VERSION = "1.0"
TOOL_VERSION = "1.0"

#: Only the VLM-judged predicates are labelled. canPierce and canPourInto are
#: rule-based (see _RULE_BASED_PREDICATES in vlm.py) — there is no teacher
#: judgment to compare a human against, so labelling them could not measure
#: teacher quality. Derived from vlm.py rather than restated, so the two can
#: never drift apart.
LABELLED_PREDICATES: tuple[str, ...] = tuple(VLM_PREDICATES)

#: Substrings that mark a field as carrying the teacher's or the model's
#: answer. Matched case-insensitively against every key in the pair list, at
#: any nesting depth. Deliberately broad: a false rejection is a one-line fix
#: to a pair-list generator, whereas a false acceptance silently invalidates
#: the experiment.
BLIND_FIELD_PATTERNS: tuple[str, ...] = (
    "score", "label", "vlm", "predict", "pred_", "_pred",
    "rationale", "logit", "prob", "confidence_model", "teacher", "gt",
)

#: Exact key names that are answer-bearing but whose substrings cannot safely
#: go in BLIND_FIELD_PATTERNS — "pred" as a substring would reject the wholly
#: legitimate `predicate` key on every valid pair list.
_BLIND_EXACT: frozenset[str] = frozenset({"pred", "y", "target", "truth"})

#: `predicate` and `pair_dir` legitimately contain blind substrings ("pred").
#: Exact-name allowlist, checked before the substring scan.
_BLIND_EXEMPT: frozenset[str] = frozenset({
    "predicate", "pair_dir", "pair_id", "pair_list_version",
})

_REQUIRED_PAIR_FIELDS = ("pair_id", "actor", "recipient", "predicate")

#: Answers faster than this are flagged for audit, never blocked — a fast
#: answer on an obvious pair is legitimate, but a run of them is worth seeing.
FAST_ANSWER_MS = 800

VERDICTS = ("yes", "no", "unsure")


class PairListError(ValueError):
    """The pair list is structurally invalid."""


class BlindnessViolation(PairListError):
    """The pair list carries the VLM label or the model prediction.

    Raised rather than stripped: a generator that emitted these fields once may
    emit them again somewhere the tool does not look, so this must fail loudly
    at the source.
    """


# ---------------------------------------------------------------------------
# Pair list
# ---------------------------------------------------------------------------

def _blind_hits(obj: Any, path: str = "") -> list[str]:
    """Every key anywhere in `obj` that looks like an answer-bearing field."""
    hits: list[str] = []
    if isinstance(obj, dict):
        for key, value in obj.items():
            here = f"{path}.{key}" if path else str(key)
            if key not in _BLIND_EXEMPT:
                low = str(key).lower()
                if low in _BLIND_EXACT or any(
                        pat in low for pat in BLIND_FIELD_PATTERNS):
                    hits.append(here)
            hits.extend(_blind_hits(value, here))
    elif isinstance(obj, list):
        for i, value in enumerate(obj):
            hits.extend(_blind_hits(value, f"{path}[{i}]"))
    return hits


def load_pair_list(path: Path | str) -> list[dict]:
    """Load and validate a pair list, enforcing labeller blindness.

    Returns the `pairs` array. The caller gets `pair_list_version` from
    `read_pair_list_version` (kept separate so records can stamp it).
    """
    path = Path(path)
    try:
        doc = json.loads(path.read_text())
    except json.JSONDecodeError as exc:
        raise PairListError(f"{path} is not valid JSON: {exc}") from exc

    if not isinstance(doc, dict) or "pairs" not in doc:
        raise PairListError(f"{path} must be an object with a 'pairs' array")
    if not doc.get("pair_list_version"):
        raise PairListError(
            f"{path} is missing 'pair_list_version' — records must be traceable "
            "to the selection that produced them")

    hits = _blind_hits(doc)
    if hits:
        raise BlindnessViolation(
            f"{path} carries answer-bearing field(s): {', '.join(sorted(hits))}. "
            "The labeller must be blind to the VLM label and the model "
            "prediction (tools/docs/labeling_protocol.md §2); join them offline "
            "on pair_id instead.")

    pairs = doc["pairs"]
    if not isinstance(pairs, list) or not pairs:
        raise PairListError(f"{path} contains no pairs")

    seen: set[str] = set()
    for i, pair in enumerate(pairs):
        if not isinstance(pair, dict):
            raise PairListError(f"pair {i} is not an object")
        for field in _REQUIRED_PAIR_FIELDS:
            if field not in pair:
                raise PairListError(f"pair {i} is missing required field {field!r}")
        pred = pair["predicate"]
        if pred not in LABELLED_PREDICATES:
            raise PairListError(
                f"pair {i} has predicate {pred!r}, which is not labelled by hand. "
                f"Expected one of {list(LABELLED_PREDICATES)} — canPierce and "
                "canPourInto are rule-based, not VLM-judged, so a human label "
                "on them cannot measure teacher quality.")
        pid = pair["pair_id"]
        if pid in seen:
            raise PairListError(f"duplicate pair_id {pid!r}")
        seen.add(pid)

    return pairs


def read_pair_list_version(path: Path | str) -> str:
    return json.loads(Path(path).read_text())["pair_list_version"]


def compute_pair_id(actor: str, recipient: str, predicate: str, version: str) -> str:
    """Stable content hash — the only key needed to join a human label against
    the VLM's label and the model's prediction after the session. Order
    matters: pairs are ordered, so (a,b) and (b,a) must never collide."""
    raw = "\x1f".join([actor, recipient, predicate, version])
    return "sha1:" + hashlib.sha1(raw.encode()).hexdigest()[:16]


# ---------------------------------------------------------------------------
# What the labeller is shown
# ---------------------------------------------------------------------------

def definition_for(predicate: str) -> str:
    """The predicate definition, assembled live from prompts.py.

    Imported rather than copied on purpose: the human must be answering the
    same question the VLM was asked, and a copy-pasted definition would drift
    silently the next time the prompt is tuned, invalidating the comparison
    without any visible failure.
    """
    if predicate not in LABELLED_PREDICATES:
        raise KeyError(
            f"{predicate!r} is rule-based and is not hand-labelled; "
            f"expected one of {list(LABELLED_PREDICATES)}")
    return f"{AFFORDANCE_QUESTION[predicate]}\n\n{_CALIBRATION[predicate]}"


def grid_image_name(predicate: str) -> str:
    """Which rendered image the VLM actually saw for this predicate.

    canCut was re-labelled from a bespoke composite (two paired angles plus two
    solo close-up tiles) built during the knife-type fix so blade detail was
    visible; the other predicates used the standard multi-angle contact sheet.
    Showing the human a different image than the teacher saw would turn a
    judgment difference into a viewing-condition difference.
    """
    return "cancut_grid.png" if predicate == "canCut" else "grid.png"


# ---------------------------------------------------------------------------
# Records
# ---------------------------------------------------------------------------

#: The VLM's own yes/no cutoff (see scripts/make_pair_list.py's
#: VLM_THRESHOLD) -- reused so a derived verdict is comparable to the
#: teacher's, not an arbitrary different cutoff.
_HUMAN_SCORE_THRESHOLD = 5


def make_record(pair: dict, verdict: str | None, *, confidence: int | None,
                confidence_explicit: bool, note: str, elapsed_ms: int,
                pair_list_version: str, session_id: str, labeller: str,
                revision_of: str | None = None,
                human_score: int | None = None) -> dict:
    """One judgement. Carries enough provenance to reproduce the selection and
    to join against the teacher's labels offline.

    Two labelling modes, mutually exclusive:
      - legacy binary: pass `verdict` ("yes"/"no"/"unsure"), leave
        `human_score` unset.
      - graded (2026-08-03): pass `human_score` (0-9, same scale as the VLM
        prompt), leave `verdict` as None -- a binary yes/no can't distinguish
        "structurally capable, however poorly" (e.g. a box cutter CAN cut a
        melon) from "a good fit for this job", and the model's own score is
        graded quality-of-fit, matching the VLM training label. `verdict` is
        derived automatically at the same cutoff the VLM's own labels use.
    """
    if human_score is not None and verdict is not None:
        raise ValueError("pass exactly one of verdict or human_score, not both")
    if human_score is not None:
        if not (0 <= human_score <= 9):
            raise ValueError(f"human_score must be 0-9, got {human_score!r}")
        verdict = "yes" if human_score >= _HUMAN_SCORE_THRESHOLD else "no"
    elif verdict not in VERDICTS:
        raise ValueError(f"verdict must be one of {VERDICTS}, got {verdict!r}")

    flags: list[str] = []
    if elapsed_ms < FAST_ANSWER_MS:
        flags.append("fast_answer")
    if note.strip():
        flags.append("has_note")

    return {
        "schema_version": SCHEMA_VERSION,
        "tool_version": TOOL_VERSION,
        "pair_id": pair["pair_id"],
        "pair_list_version": pair_list_version,
        "scene_id": pair.get("scene_id"),
        "pair_dir": pair.get("pair_dir"),
        "actor": pair["actor"],
        "recipient": pair["recipient"],
        "predicate": pair["predicate"],
        "split_level": pair.get("split_level"),
        "verdict": verdict,
        "human_score": human_score,
        # Defaults to 3 when skipped, per the protocol. `confidence_explicit`
        # keeps a skipped value distinguishable from a deliberate 3 — without
        # it the field would quietly overstate certainty across the session.
        "confidence": 3 if confidence is None else int(confidence),
        "confidence_explicit": bool(confidence_explicit),
        "note": note,
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "elapsed_ms": int(elapsed_ms),
        "flags": flags,
        "session_id": session_id,
        "labeller": labeller,
        "revision_of": revision_of,
    }


def append_record(path: Path | str, record: dict) -> None:
    """Append one judgement and flush to disk immediately.

    Append-only JSONL with a per-record flush: a crash costs at most the
    in-flight item, and the user will not redo a session lost to one.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(record, ensure_ascii=False) + "\n")
        fh.flush()


def load_session(path: Path | str) -> list[dict]:
    """Read a session back, tolerating a truncated final line from a crash."""
    path = Path(path)
    if not path.exists():
        return []
    out: list[dict] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            out.append(json.loads(line))
        except json.JSONDecodeError:
            # Only ever the last line, from a crash mid-write. Everything
            # before it is complete and must stay recoverable.
            continue
    return out


def remaining_items(items: Iterable[dict], records: Iterable[dict]) -> list[dict]:
    """Items still to judge. Revisions supersede by pair_id, so a re-answered
    item is not offered again."""
    done = {r["pair_id"] for r in records}
    return [i for i in items if i["pair_id"] not in done]


# ---------------------------------------------------------------------------
# Server
# ---------------------------------------------------------------------------

_HTML = (Path(__file__).parent / "manual_tool.html")

#: Bytes cached per image so flipping between angles on an already-viewed
#: item doesn't re-fetch over SSH every time. Session-lifetime, in-process --
#: fine here since the tool is one labeller, one browser tab, one run.
@lru_cache(maxsize=512)
def _fetch_remote_image(remote_host: str, remote_path: str) -> bytes | None:
    """`ssh <host> cat <remote_path>`, bytes on success, None on any failure
    (missing file, network hiccup) -- the caller turns that into a 404, same
    contract as a local Path.exists() miss."""
    try:
        result = subprocess.run(
            ["ssh", remote_host, "cat", remote_path],
            capture_output=True, timeout=30, check=False,
        )
    except (subprocess.TimeoutExpired, OSError):
        return None
    return result.stdout if result.returncode == 0 and result.stdout else None


def _payload(items: list[dict], done: int, total: int, graded: bool = False) -> dict:
    """What the page needs. Assembled field-by-field rather than passing the
    pair through, so a stray key in the pair list can never reach the UI.

    `graded` (2026-08-03): switches the UI from yes/no/unsure to a 0-9
    quality score (see make_record's human_score) -- a binary verdict can't
    distinguish "structurally capable, however poorly" from "a good fit",
    which the model's own graded score does distinguish."""
    return {
        "items": [
            {
                "pair_id": i["pair_id"],
                "actor": i["actor"],
                "recipient": i["recipient"],
                "predicate": i["predicate"],
                "question": AFFORDANCE_QUESTION[i["predicate"]],
                "definition": definition_for(i["predicate"]),
                "image": grid_image_name(i["predicate"]),
                "pair_dir": i.get("pair_dir", ""),
                "angles": i.get("angles", []),
            }
            for i in items
        ],
        "done": done,
        "total": total,
        "graded": graded,
    }


def build_handler(state: dict):
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *a):  # keep the console quiet during a session
            pass

        def _send(self, code, body, ctype="application/json"):
            data = body if isinstance(body, bytes) else body.encode("utf-8")
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)

        def do_GET(self):
            if self.path in ("/", "/index.html"):
                return self._send(200, _HTML.read_text(), "text/html; charset=utf-8")
            if self.path == "/api/state":
                # Recomputed live from the on-disk session file, not the
                # snapshot taken at server boot -- a browser refresh must see
                # every judgement saved since startup (including ones from
                # a DIFFERENT tab/process against the same --out file), not
                # silently rewind to idx 0 against a stale "done" count.
                records = load_session(state["out"])
                todo = remaining_items(state["items"], records)
                payload = _payload(todo, len(records), len(state["items"]),
                                   graded=state["graded"])
                return self._send(200, json.dumps(payload))
            if self.path.startswith("/img/"):
                rel = self.path[len("/img/"):].split("?")[0]
                if state.get("remote_host"):
                    # No local copy at all -- fetched live over SSH each
                    # time (cached in-process by _fetch_remote_image), so
                    # the render tree never has to fit on local disk.
                    remote_path = f"{state['remote_renders_root'].rstrip('/')}/{rel}"
                    data = _fetch_remote_image(state["remote_host"], remote_path)
                    if data is None:
                        return self._send(404, b"missing (remote)", "text/plain")
                    return self._send(200, data, "image/png")
                img = (state["renders"] / rel).resolve()
                # Path containment check: the renders dir is the only thing
                # this server is allowed to serve.
                if not str(img).startswith(str(state["renders"].resolve())):
                    return self._send(403, b"forbidden", "text/plain")
                if not img.exists():
                    return self._send(404, b"missing", "text/plain")
                return self._send(200, img.read_bytes(), "image/png")
            return self._send(404, b"not found", "text/plain")

        def do_POST(self):
            if self.path != "/api/judge":
                return self._send(404, b"not found", "text/plain")
            n = int(self.headers.get("Content-Length", 0))
            body = json.loads(self.rfile.read(n) or b"{}")
            pair = state["by_id"].get(body.get("pair_id"))
            if pair is None:
                return self._send(400, json.dumps({"error": "unknown pair_id"}))
            rec = make_record(
                pair, body.get("verdict"),
                confidence=body.get("confidence"),
                confidence_explicit=bool(body.get("confidence_explicit")),
                note=body.get("note", ""),
                elapsed_ms=body.get("elapsed_ms", 0),
                pair_list_version=state["pair_list_version"],
                session_id=state["session_id"],
                human_score=body.get("human_score"),
                labeller=state["labeller"],
                revision_of=body.get("revision_of"),
            )
            append_record(state["out"], rec)
            state["done"] += 1
            return self._send(200, json.dumps({"ok": True, "done": state["done"]}))

    return Handler


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--pairs", required=True, help="pair list JSON")
    ap.add_argument("--out", required=True, help="output JSONL (appended)")
    ap.add_argument("--renders",
                    help="dir of <actor>__<recipient>/ render dirs "
                         "(local disk). Required unless --remote-host is set.")
    ap.add_argument("--remote-host", default=None,
                    help="ssh host (as in `ssh <host>`, e.g. an entry from "
                         "~/.ssh/config) to fetch render images from live, "
                         "instead of requiring a local copy under --renders. "
                         "Each /img/ request runs `ssh <host> cat <path>` and "
                         "caches the bytes in-process -- no local render tree "
                         "needed, useful when local disk can't hold it.")
    ap.add_argument("--remote-renders",
                    help="remote dir of <actor>__<recipient>/ render dirs on "
                         "--remote-host (e.g. /scratch/user/affdet/"
                         "pair_renders_full). Required when --remote-host is set.")
    ap.add_argument("--labeller", default="max")
    ap.add_argument("--session-id", default=None)
    ap.add_argument("--port", type=int, default=8765)
    ap.add_argument("--no-browser", action="store_true")
    ap.add_argument("--graded", action="store_true",
                    help="0-9 quality score instead of yes/no/unsure "
                         "(see make_record's human_score)")
    args = ap.parse_args(argv)

    if args.remote_host and not args.remote_renders:
        ap.error("--remote-renders is required when --remote-host is set")
    if not args.remote_host and not args.renders:
        ap.error("--renders is required unless --remote-host is set")

    items = load_pair_list(args.pairs)
    version = read_pair_list_version(args.pairs)
    records = load_session(args.out)
    todo = remaining_items(items, records)

    if not todo:
        print(f"All {len(items)} items already judged in {args.out}. Nothing to do.")
        return 0

    session_id = args.session_id or datetime.now().strftime("%Y-%m-%d-%H%M")
    state = {
        "items": items,
        "graded": args.graded,
        "by_id": {i["pair_id"]: i for i in items},
        "out": Path(args.out),
        "renders": Path(args.renders) if args.renders else None,
        "remote_host": args.remote_host,
        "remote_renders_root": args.remote_renders,
        "pair_list_version": version,
        "session_id": session_id,
        "labeller": args.labeller,
        "done": len(records),
    }

    # Sidecar: makes the session reproducible and auditable after the fact.
    meta = Path(args.out).with_suffix(".meta.json")
    meta.write_text(json.dumps({
        "session_id": session_id,
        "labeller": args.labeller,
        "pair_list": str(args.pairs),
        "pair_list_version": version,
        "pair_list_sha1": hashlib.sha1(Path(args.pairs).read_bytes()).hexdigest(),
        "schema_version": SCHEMA_VERSION,
        "tool_version": TOOL_VERSION,
        "protocol": "tools/docs/labeling_protocol.md",
        "started_utc": datetime.now(timezone.utc).isoformat(),
        "n_total": len(items),
        "n_already_done": len(records),
    }, indent=2))

    url = f"http://127.0.0.1:{args.port}/"
    print(f"{len(todo)} of {len(items)} items remaining -> {url}")
    print(f"writing to {args.out} (autosaved after every judgement)")
    if not args.no_browser:
        webbrowser.open(url)
    srv = HTTPServer(("127.0.0.1", args.port), build_handler(state))
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        print(f"\nstopped — {state['done']}/{len(items)} judged, all saved.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
