# ---------------------------------------------------------------------------
# Template definitions
# Each template is a function (rng, inventory) -> list of role specs
# Role spec: (category_pool, placement_variant, container_slot)
#   placement_variant: "whole" | "piece" | "any" | "table"
#   container_slot: None (table) or index into containers list
# ---------------------------------------------------------------------------

# T1 — Fruit bowl: large bowl + 2 small whole fruits + 1 knife
def _t1(rng, inv):
    fruits = inv.pick_whole(rng, _SMALL_FOOD, n=2)
    return [
        ("bowl",   "container", None),
        (fruits[0], "whole",    0),
        (fruits[1], "whole",    0),
        ("knife",  "utensil",   None),
    ]

# T2 — Prep scene: 1 whole large food on table + 1-2 knives
def _t2(rng, inv):
    food = inv.pick_whole(rng, _LARGE_FOOD, n=1)
    n_knives = rng.randint(1, 3)
    return [(food[0], "table", None)] + [("knife", "utensil", None)] * n_knives

# T3 — Plate with pieces: dish + 1-2 piece foods + fork + knife
def _t3(rng, inv):
    pieces = inv.pick_piece(rng, _PIECE_ONLY | _MEDIUM_FOOD, n=rng.randint(1, 3))
    rows = [("dish", "container", None)]
    for i, p in enumerate(pieces):
        rows.append((p, "piece", 0))
    rows += [("fork", "utensil", None), ("knife", "utensil", None)]
    return rows

# T4 — Mixed prep: dish with pieces + whole large food on table + knife + fork
def _t4(rng, inv):
    pieces = inv.pick_piece(rng, _PIECE_ONLY | _MEDIUM_FOOD, n=rng.randint(1, 3))
    large = inv.pick_whole(rng, _LARGE_FOOD, n=1)
    rows = [("dish", "container", None)]
    for p in pieces:
        rows.append((p, "piece", 0))
    rows += [(large[0], "table", None), ("knife", "utensil", None), ("fork", "utensil", None)]
    return rows

# T5 — Cup/glass scene: 2 cups or 1-2 wine glasses + tiny foods dropped in + fork
def _t5(rng, inv):
    use_glass = rng.rand() < 0.5
    container = "red_wine_glass" if use_glass else "cup"
    n_containers = rng.randint(1, 3)
    tinies = inv.pick_whole(rng, _TINY_FOOD, n=n_containers)
    rows = [(container, "container", None) for _ in range(n_containers)]
    for i, t in enumerate(tinies):
        rows.append((t, "whole", i))
    rows.append(("fork", "utensil", None))
    return rows

# T6 — Pan scene: pan + 2 mixed foods + knife + fork
def _t6(rng, inv):
    foods = inv.pick_any(rng, _MEDIUM_FOOD | _SMALL_FOOD, n=rng.randint(1, 3))
    rows = [("pan", "container", None)]
    for f in foods:
        rows.append((f, "any", 0))
    rows += [("knife", "utensil", None), ("fork", "utensil", None)]
    return rows

# T7 — Tea setup: teapot/kettle + 2-3 cups + small foods in bowl
def _t7(rng, inv):
    pourable = rng.choice(["teapot", "kettle"])
    n_cups = rng.randint(2, 4)
    foods = inv.pick_whole(rng, _SMALL_FOOD, n=rng.randint(1, 3))
    rows = [(pourable, "pourable", None), ("bowl", "container", None)]
    rows += [("cup", "container", None) for _ in range(n_cups)]
    for f in foods:
        rows.append((f, "whole", 1))  # slot 1 = bowl
    return rows

# T8 — Bottle scene: 1-2 bottles/vases + cup/bowl + small whole foods + knife
def _t8(rng, inv):
    pourable = rng.choice(["bottle", "vase"])
    n_pourables = rng.randint(1, 3)
    container = rng.choice(["cup", "bowl"])
    foods = inv.pick_whole(rng, _SMALL_FOOD | _TINY_FOOD, n=rng.randint(1, 3))
    rows = [(pourable, "pourable", None) for _ in range(n_pourables)]
    rows.append((container, "container", None))
    for f in foods:
        rows.append((f, "whole", n_pourables))  # slot after pourables = container
    rows.append(("knife", "utensil", None))
    return rows

# T9 — Busy kitchen: bowl + dish + pourable + foods + utensils + scissor prop
def _t9(rng, inv):
    pourable = rng.choice(["teapot", "bottle", "kettle", "vase"])
    bowl_foods = inv.pick_whole(rng, _SMALL_FOOD, n=rng.randint(1, 3))
    dish_foods = inv.pick_piece(rng, _PIECE_ONLY | _MEDIUM_FOOD, n=rng.randint(1, 3))
    rows = [
        ("bowl",  "container", None),
        ("dish",  "container", None),
        (pourable, "pourable", None),
    ]
    for f in bowl_foods:
        rows.append((f, "whole", 0))
    for f in dish_foods:
        rows.append((f, "piece", 1))
    rows += [("knife", "utensil", None), ("fork", "utensil", None), ("scissor", "utensil", None)]
    return rows

# T10 — Salad bowl: large bowl + 1-2 piece vegetables + fork + knife
def _t10(rng, inv):
    veg_pool = {"cucumber", "carrot", "broccoli", "broccolini", "onion", "mushroom", "potato"}
    pieces = inv.pick_piece(rng, veg_pool, n=rng.randint(1, 3))
    rows = [("bowl", "container", None)]
    for p in pieces:
        rows.append((p, "piece", 0))
    rows += [("fork", "utensil", None), ("knife", "utensil", None)]
    return rows

# T11 — Dessert plate: dish + 1-2 sweet pieces + fork
def _t11(rng, inv):
    sweets = {"cake", "donut", "bun", "strawberry", "fig", "dumpling"}
    foods = inv.pick_any(rng, sweets, n=rng.randint(1, 3))
    rows = [("dish", "container", None)]
    for f in foods:
        rows.append((f, "any", 0))
    rows.append(("fork", "utensil", None))
    return rows

# T12 — Whole veg on table: 2-3 whole veg + 1-2 knives, no container
def _t12(rng, inv):
    veg_pool = {"carrot", "cucumber", "potato", "sweet_potato", "ginger",
                "onion", "tomato", "garlic", "lemon"}
    vegs = inv.pick_whole(rng, veg_pool, n=rng.randint(2, 4))
    n_knives = rng.randint(1, 3)
    return [(v, "table", None) for v in vegs] + [("knife", "utensil", None)] * n_knives


