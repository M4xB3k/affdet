class _Inventory:
    """Resolves category+variant to a specific instance ID from curation.json."""

    def __init__(self, curation: dict, omni_root: Path, rng: np.random.RandomState):
        self._cur = curation
        self._root = omni_root
        self._rng = rng
        # Pre-build: cat → {"whole": [...], "piece": [...], "any": [...]}
        self._instances: dict[str, dict[str, list[str]]] = {}
        self._build()

    def _build(self):
        for cat, entry in self._cur.items():
            if cat.startswith("_") or not isinstance(entry, dict):
                continue
            drops = set(entry.get("drop", []))
            recats = set(
                entry.get("recategorize", {}).keys()
                if isinstance(entry.get("recategorize"), dict) else []
            )
            excluded = drops | recats
            p = entry.get("placement", {})
            whole = [i for i in p.get("whole", []) if i not in excluded
                     and self._mesh_exists(cat, f"{cat}_{i}")]
            piece = [i for i in p.get("piece", []) if i not in excluded
                     and self._mesh_exists(cat, f"{cat}_{i}")]
            # If no placement split, discover from extracted dir
            if not whole and not piece:
                ext_dir = self._root / cat / "extracted"
                if ext_dir.exists():
                    all_ids = [
                        d.name.split("_")[-1] for d in sorted(ext_dir.iterdir())
                        if self._mesh_exists(cat, d.name) and d.name.split("_")[-1] not in excluded
                    ]
                    whole = all_ids
            self._instances[cat] = {
                "whole": whole,
                "piece": piece,
                "any":   list(dict.fromkeys(whole + piece)),  # deduplicated
            }

    def _mesh_exists(self, cat: str, instance_id: str) -> bool:
        return (self._root / cat / "extracted" / instance_id / "Scan" / "Scan.obj").exists()

    def _pick(self, cat: str, variant: str) -> str | None:
        ids = self._instances.get(cat, {}).get(variant, [])
        if not ids:
            # fallback to "any"
            ids = self._instances.get(cat, {}).get("any", [])
        if not ids:
            return None
        idx = int(self._rng.randint(len(ids)))
        return f"{cat}_{ids[idx]}"

    def pick_whole(self, rng, pool: set[str], n: int) -> list[str]:
        available = [c for c in pool if self._instances.get(c, {}).get("whole") or
                     self._instances.get(c, {}).get("any")]
        rng.shuffle(available)
        result = []
        for cat in available:
            if len(result) >= n:
                break
            inst = self._pick(cat, "whole")
            if inst:
                result.append(inst)
        return result

    def pick_piece(self, rng, pool: set[str], n: int) -> list[str]:
        available = [c for c in pool if self._instances.get(c, {}).get("piece") or
                     self._instances.get(c, {}).get("any")]
        rng.shuffle(available)
        result = []
        for cat in available:
            if len(result) >= n:
                break
            inst = self._pick(cat, "piece")
            if inst:
                result.append(inst)
        return result

    def pick_any(self, rng, pool: set[str], n: int) -> list[str]:
        available = [c for c in pool if self._instances.get(c, {}).get("any")]
        rng.shuffle(available)
        result = []
        for cat in available:
            if len(result) >= n:
                break
            inst = self._pick(cat, "any")
            if inst:
                result.append(inst)
        return result

    def pick_actor(self, cat: str) -> str | None:
        """Pick any available instance of an actor/container/pourable."""
        return self._pick(cat, "any")

    def open_instances(self, cat: str) -> list[str]:
        """Return open instances for a container (from open_closed.open)."""
        entry = self._cur.get(cat, {})
        open_ids = entry.get("open_closed", {}).get("open", [])
        drops = set(entry.get("drop", []))
        recats = set(entry.get("recategorize", {}).keys()
                     if isinstance(entry.get("recategorize"), dict) else [])
        excluded = drops | recats
        return [
            f"{cat}_{i}" for i in open_ids
            if i not in excluded and self._mesh_exists(cat, f"{cat}_{i}")
        ]


@dataclass
class OmniSceneSampler:
    curation_path: Path | str
    omni_root: Path | str
    seed: int = 0
    min_gap_m: float = 0.04

    _rng: np.random.RandomState = field(init=False, repr=False)
    _curation: dict = field(init=False, repr=False)
    _inv: _Inventory = field(init=False, repr=False)
    _template_idx: int = field(init=False, repr=False, default=0)

    def __post_init__(self) -> None:
        self._rng = np.random.RandomState(self.seed)
        self.omni_root = Path(self.omni_root)
        with open(self.curation_path) as f:
            self._curation = json.load(f)
        self._inv = _Inventory(self._curation, self.omni_root, self._rng)

    def sample(self) -> OmniSceneConfig | None:
        # Cycle through templates in shuffled order for variety
        t_idx = self._template_idx % len(_TEMPLATES)
        self._template_idx += 1
        name, fn = _TEMPLATES[t_idx]

        rows = fn(self._rng, self._inv)
        if not rows:
            return None
        return self._build_scene(rows, name)

    def _build_scene(self, rows: list[tuple], name: str) -> OmniSceneConfig | None:
        """Resolve template rows (cat_or_instance, variant, container_slot) into
        a placed OmniSceneConfig. Shared by the round-robin sample() and the
        coverage-aware sampler."""
        # Resolve rows to placements
        # First pass: resolve containers and pourables (they go on table)
        containers: list[OmniObjectPlacement] = []
        utensils: list[OmniObjectPlacement] = []
        foods: list[tuple[OmniObjectPlacement, int | None]] = []  # (placement, container_slot)

        for row in rows:
            cat_or_id, variant, container_slot = row
            # cat_or_id may already be a resolved instance (e.g. "knife_003",
            # "red_wine_glass_007") or a bare category name (e.g. "knife"). An
            # instance id ends with "_<digits>"; a category never does.
            _tail = cat_or_id.rsplit("_", 1)
            if len(_tail) == 2 and _tail[1].isdigit():
                cat = _tail[0]
                inst_id = cat_or_id
            else:
                cat = cat_or_id
                if cat in _CONTAINERS:
                    # Use open instances for canContain actors
                    open_ids = self._inv.open_instances(cat)
                    if open_ids:
                        inst_id = open_ids[int(self._rng.randint(len(open_ids)))]
                    else:
                        inst_id = self._inv.pick_actor(cat)
                elif cat in _POURABLES or cat in _UTENSILS or cat == "scissor":
                    inst_id = self._inv.pick_actor(cat)
                else:
                    inst_id = self._inv.pick_actor(cat)

            if inst_id is None:
                continue

            mesh = self._mesh_path(cat, inst_id)
            if not mesh.exists():
                continue

            p = OmniObjectPlacement(
                obj_class=cat,
                instance_id=inst_id,
                mesh_path=str(mesh),
                position=[0.0, 0.0, TABLE_HEIGHT_M + 0.15],
                rotation_euler=self._random_rotation(),
                container_idx=container_slot,
            )

            if variant == "container":
                containers.append(p)
            elif variant == "pourable":
                utensils.append(p)  # pourables go on table like utensils
            elif variant == "utensil":
                utensils.append(p)
            else:
                foods.append((p, container_slot))

        if not (containers + utensils) and not foods:
            return None

        all_placements = containers + utensils + [f for f, _ in foods]
        all_placements = self._assign_positions(all_placements)

        # Attach container_idx back to food placements so blender can drop into container
        food_objects = [f for f, _ in foods]
        for i, (fp, slot) in enumerate(foods):
            if slot is not None and slot < len(containers):
                food_objects[i].container_idx = slot

        return OmniSceneConfig(
            objects=all_placements,
            camera_pose=self._sample_camera_pose(),
            template_name=name,
        )

    def sample_covered(self, tracker, index):
        """Coverage-aware scene: pick the most under-covered (affordance, bucket),
        build a scene guaranteed to contain that pair, and return
        (config, realised, required):
          - realised: (affordance, bucket) pairs the scene realises (for tracker)
          - required: instance ids that MUST be visible for the pair to be valid
            (the actor, plus the container for pour/support) — the caller checks
            these against the final-render visibility and re-renders if occluded.
        Returns (None, [], set()) when all targets are met.

        canPourInto is composition-driven: pos = pourable + open container,
        neg = pourable + closed container. All other affordances pull a concrete
        (actor_instance, food_category) pair from the label index.
        """
        # Try under-covered targets in deficit order; skip any that cannot be
        # built right now (missing meshes/instances) so we never livelock.
        skip: set[tuple[str, str]] = set()
        while True:
            target = tracker.weighted_target(self._rng, skip)
            if target is None:
                return None, [], set()
            aff, bucket = target

            if aff == POURINTO:
                rows, realised, required = self._pourinto_rows(bucket)
            else:
                rows, realised, required = self._pair_rows(aff, bucket, index)

            config = self._build_scene(rows, f"cov_{aff}_{bucket}") if rows else None
            # Reject the scene unless every instance the affordance NEEDS (the
            # actor, and the container for pour/support) actually made it in —
            # otherwise we'd emit e.g. a lone food that doesn't express the
            # affordance at all.
            if config is not None:
                present = {p.instance_id for p in config.objects}
                if not required.issubset(present):
                    config = None
            if config is None:
                skip.add(target)
                continue

            for p in config.objects:
                tracker.record_instance(p.instance_id)
            return config, realised, required

    def _pair_rows(self, aff: str, bucket: str, index):
        """Build rows around a labelled (actor_instance, food_cat) pair for a
        VLM affordance. Adds a container when the affordance needs one, plus a
        filler food, so the scene is a plausible small kitchen vignette."""
        pool = index.pairs.get(aff, {}).get(bucket, [])
        if not pool:
            return [], [], set()
        actor_inst, food_cat = pool[int(self._rng.randint(len(pool)))]
        # Strip face/part suffixes (pan_001_diag -> pan_001) so the mesh path
        # resolves, then remap peeler_NNN -> knife_NNN (peelers live under knife/).
        actor_inst = normalize_actor_id(actor_inst)
        if actor_inst.startswith("peeler_"):
            actor_inst = actor_inst.replace("peeler_", "knife_", 1)
        actor_cat = index.actor_category(actor_inst)

        rows: list[tuple] = []
        # Container-based affordances: actor IS the container, food goes in it.
        if aff in ("canContain", "canSupport"):
            rows.append((actor_inst, "container", None))
            variant = "piece" if food_cat in _PIECE_ONLY else "whole"
            rows.append((food_cat, variant, 0))
        else:
            # Tool affordances (canCut/canPierce/canPeel): actor is a utensil,
            # food sits on the table next to it.
            rows.append((actor_inst, "utensil", None))
            variant = "piece" if food_cat in _PIECE_ONLY else "whole"
            rows.append((food_cat, variant, None))
        rows += self._filler_rows(exclude_cat=actor_cat)
        return rows, [(aff, bucket)], {actor_inst}

    def _filler_rows(self, exclude_cat: str | None = None) -> list[tuple]:
        """A few extra plausible objects so coverage scenes look like real
        kitchen tables (not a bare actor+food pair) and yield more pairs per
        render. Adds 1-3 random foods/utensils/containers on the table."""
        n = int(self._rng.randint(1, 4))  # 1..3 extra objects
        pools = [
            (list(_SMALL_FOOD | _MEDIUM_FOOD), "whole"),
            (["knife", "fork"], "utensil"),
            (["bowl", "dish"], "container"),
        ]
        rows: list[tuple] = []
        for _ in range(n):
            cats, variant = pools[int(self._rng.randint(len(pools)))]
            cat = cats[int(self._rng.randint(len(cats)))]
            if cat == exclude_cat:
                continue
            rows.append((cat, variant, None))
        return rows

    def _pourinto_rows(self, bucket: str):
        """canPourInto scene: a pourable + a container. pos = OPEN container
        (pour succeeds), neg = CLOSED container (e.g. a sealed bottle — pour
        cannot happen)."""
        pourable = self._rng.choice(sorted(_POURABLES))
        pourable_inst = self._inv.pick_actor(pourable)
        if pourable_inst is None:
            return [], [], set()
        rows: list[tuple] = [(pourable_inst, "pourable", None)]

        want_open = bucket == "pos"
        container_inst = self._pick_container_by_openness(open_wanted=want_open)
        if container_inst is None:
            return [], [], set()
        rows.append((container_inst, "container", None))
        rows += self._filler_rows(exclude_cat=pourable)
        # Both the pourable and the target container must be present for the
        # canPourInto relation to be expressed.
        return rows, [(POURINTO, bucket)], {pourable_inst, container_inst}

    def _pick_container_by_openness(self, open_wanted: bool) -> str | None:
        """Pick a container instance that is open (for pos) or closed (for neg),
        drawing from every container/pourable category that has such instances."""
        cats = sorted(_CONTAINERS | _POURABLES)
        self._rng.shuffle(cats)
        for cat in cats:
            entry = self._curation.get(cat, {})
            oc = entry.get("open_closed", {})
            ids = oc.get("open" if open_wanted else "closed", [])
            drops = set(entry.get("drop", []))
            avail = [f"{cat}_{i}" for i in ids
                     if i not in drops and self._mesh_path(cat, f"{cat}_{i}").exists()]
            if avail:
                return avail[int(self._rng.randint(len(avail)))]
        return None

    def _mesh_path(self, cat: str, instance_id: str) -> Path:
        return self.omni_root / cat / "extracted" / instance_id / "Scan" / "Scan.obj"

    def _random_rotation(self) -> list[float]:
        rx = float(self._rng.uniform(-math.pi / 8, math.pi / 8))
        ry = float(self._rng.uniform(-math.pi / 8, math.pi / 8))
        rz = float(self._rng.uniform(0.0, 2.0 * math.pi))
        return [rx, ry, rz]

    def _assign_positions(self, placements: list[OmniObjectPlacement]) -> list[OmniObjectPlacement]:
        table_w, table_d = TABLE_SIZE_M
        margin = 0.08
        occupied: list[tuple[float, float, float, float]] = []

        for p in placements:
            fw, fd = _footprint(p.obj_class)
            hw, hd = fw / 2, fd / 2
            pos = None
            for _ in range(500):
                x = float(self._rng.uniform(-table_w / 2 + hw + margin, table_w / 2 - hw - margin))
                y = float(self._rng.uniform(-table_d / 2 + hd + margin, table_d / 2 - hd - margin))
                if not any(
                    abs(x - px) < hw + phw + self.min_gap_m and
                    abs(y - py) < hd + phd + self.min_gap_m
                    for px, py, phw, phd in occupied
                ):
                    pos = (x, y)
                    break
            if pos is None:
                pos = (
                    float(self._rng.uniform(-table_w / 4, table_w / 4)),
                    float(self._rng.uniform(-table_d / 4, table_d / 4)),
                )
            x, y = pos
            occupied.append((x, y, hw, hd))
            p.position = [x, y, TABLE_HEIGHT_M + 0.15]

        return placements

    def _sample_camera_pose(self) -> np.ndarray:
        az = float(self._rng.uniform(0.0, 2.0 * math.pi))
        el = float(self._rng.uniform(math.radians(35.0), math.radians(50.0)))
        dist = float(self._rng.uniform(1.8, 2.2))
        eye = np.array([
            dist * math.cos(el) * math.cos(az),
            dist * math.cos(el) * math.sin(az),
            dist * math.sin(el),
        ], dtype=np.float64)
        return _look_at(eye, np.zeros(3, dtype=np.float64))


def _look_at(eye: np.ndarray, target: np.ndarray,
             up: np.ndarray | None = None) -> np.ndarray:
    up = np.array([0.0, 0.0, 1.0], dtype=np.float64) if up is None else up
    forward = target - eye
    forward /= np.linalg.norm(forward) + 1e-9
    right = np.cross(forward, up)
    right /= np.linalg.norm(right) + 1e-9
    true_up = np.cross(right, forward)
    rot = np.stack([right, true_up, -forward], axis=0)
    trans = -rot @ eye
    pose = np.eye(4, dtype=np.float64)
    pose[:3, :3] = rot
    pose[:3, 3] = trans
    return pose
